export function generate12WordMnemonic(): string {
  const chosen: string[] = [];
  const wordsCount = BIP39_WORDS.length;
  for (let i = 0; i < 12; i++) {
    const randomIndex = Math.floor(Math.random() * wordsCount);
    chosen.push(BIP39_WORDS[randomIndex]);
  }
  return chosen.join(" ");
}

export function validateMnemonicPhrase(phrase: string): { isValid: boolean; error?: string } {
  const words = phrase.trim().toLowerCase().split(/\s+/);
  if (words.length !== 12) {
    return { isValid: false, error: `Must contain exactly 12 words (found ${words.length})` };
  }
  for (let i = 0; i < words.length; i++) {
    if (!BIP39_WORDS.includes(words[i])) {
      return { isValid: false, error: `Word #${i + 1} "${words[i]}" is not in the wordlist` };
    }
  }
  return { isValid: true };
}

export async function hashPhraseWithSalt(phrase: string, salt: string): Promise<string> {
  const normalized = phrase.trim().toLowerCase().split(/\s+/).join(" ");
  const text = `${normalized}:${salt}`;
  const msgUint8 = new TextEncoder().encode(text);
  const hashBuffer = await crypto.subtle.digest("SHA-256", msgUint8);
  const hashArray = Array.from(new Uint8Array(hashBuffer));
  return hashArray.map(b => b.toString(16).padStart(2, "0")).join("");
}

export function generateRandomSalt(): string {
  const arr = new Uint8Array(16);
  crypto.getRandomValues(arr);
  return Array.from(arr).map(b => b.toString(16).padStart(2, "0")).join("");
}
